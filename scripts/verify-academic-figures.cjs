'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const read=p=>fs.readFileSync(path.resolve(__dirname,'..',p),'utf8');
const root='spring-app/src/main/resources/';
const base=JSON.parse(read(root+'curriculum.json')),extra=JSON.parse(read(root+'advanced-curriculum.json'));
const modules=base.modules.concat(extra.modules),days=base.curriculum.concat(extra.curriculum);
const ctx=vm.createContext({window:{},URL});
vm.runInContext(read(root+'static/js/academic-figures-data.js'),ctx);
vm.runInContext(read(root+'static/js/academic-figures.js'),ctx);
const f=ctx.window.AgenticFigureData,ui=ctx.window.AgenticFigures;
assert.equal(f.length,16);assert.equal(ui.count,16);
assert.equal(new Set(f.map(x=>x.module)).size,16);
assert.equal(new Set(f.map(x=>x.title)).size,16);
for(const m of modules){
 const entry=f.find(x=>x.module===m.id);
 assert.ok(entry,'Missing module '+m.id);
 assert.ok(entry.days.length>=2);
 assert.ok(entry.days.every(n=>days[n-1].module===m.id),'Auto-open mapped outside module '+m.id);
 assert.equal(entry.columns.length,3);
 assert.ok(entry.columns.every(c=>c.steps.length>=4&&c.steps.every(s=>s.label&&s.detail)));
 assert.ok(entry.sources.every(s=>new URL(s).protocol==='https:'));
 const html=ui.render(m.id);
 assert.match(html,/<details class="atlas-figure atlas-roadmap"/);
 assert.match(html,/<figcaption>/);
 assert.match(html,/Further reading/);
 assert.equal((html.match(/class="atlas-lane atlas-tone-/g)||[]).length,3);
 assert.match(ui.render(m.id,entry.days[0]),/data-academic-figure="\d+" open>/);
}
const rag=ui.render(10,72);
assert.match(rag,/Offline indexing/);
assert.match(rag,/Query time/);
assert.match(rag,/Local search/);
assert.match(rag,/Global search/);
assert.match(rag,/atlas-branch/);
assert.match(ui.render(12,85),/client ↔ server/);
assert.match(ui.render(13,93),/Allowed/);
assert.match(ui.render(13,93),/Denied/);
assert.equal(ui.render(0),'');
const dashboard=read(root+'templates/dashboard.html');
const order=['/js/academic-figures-data.js','/js/academic-figures.js','/js/academic-lessons.js','/js/learning.js'].map(s=>dashboard.indexOf(s));
assert.ok(order.every((v,i)=>v>=0&&(i===0||v>order[i-1])));
assert.ok(dashboard.includes('/css/academic-figures.css'));
assert.ok(read(root+'static/js/academic-lessons.js').includes('window.AgenticFigures.render(d.module,d.day)'));
assert.ok(read(root+'static/js/learning.js').includes('window.AgenticFigures.render(m.id)'));
assert.ok(read(root+'static/css/academic-figures.css').includes('@container'));
console.log('16 module figures: valid references, matching lesson IDs, 3 panels each, semantic markup, responsive layout and integration verified.');
